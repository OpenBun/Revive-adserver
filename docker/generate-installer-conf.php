<?php

declare(strict_types=1);

/**
 * Build etc/installer.conf.php-compatible INI from environment variables.
 */

function env(string $key, ?string $default = null): ?string
{
    $v = $_ENV[$key] ?? getenv($key);
    if ($v === false || $v === null || $v === '') {
        return $default;
    }

    return (string) $v;
}

function q(string $value): string
{
    return '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], $value) . '"';
}

function applyDatabaseUrl(): void
{
    $url = env('DATABASE_URL');
    if ($url === null) {
        return;
    }

    $u = parse_url($url);
    if ($u === false || empty($u['host'])) {
        fwrite(STDERR, "Invalid DATABASE_URL\n");
        exit(1);
    }

    $scheme = strtolower($u['scheme'] ?? 'mysql');
    $type = in_array($scheme, ['pgsql', 'postgres', 'postgresql'], true) ? 'pgsql' : 'mysqli';

    $defaults = [
        'DB_TYPE' => $type,
        'DB_HOST' => $u['host'],
        'DB_PORT' => (string) ($u['port'] ?? ($type === 'pgsql' ? 5432 : 3306)),
        'DB_NAME' => ltrim($u['path'] ?? '', '/'),
        'DB_USER' => isset($u['user']) ? urldecode($u['user']) : '',
        'DB_PASSWORD' => isset($u['pass']) ? urldecode($u['pass']) : '',
    ];

    foreach ($defaults as $key => $value) {
        if (env($key) === null) {
            $_ENV[$key] = $value;
            putenv("{$key}={$value}");
        }
    }
}

applyDatabaseUrl();

